def normalizar_url(url: str) -> str:
    """Remove espaços e a barra final para facilitar a comparação."""
    return url.strip().rstrip("/")


def validar_url(url: str) -> None:
    parsed = urlparse(url)
    if parsed.scheme not in ("http", "https") or not parsed.netloc:
        raise HTTPException(status_code=400, detail="URL inválida. Use http:// ou https://")


def buscar_pagina(url: str) -> dict:
    """Procura a URL na lista mockada."""
    validar_url(url)
    alvo = normalizar_url(url)
    for pagina in PAGINAS:
        if normalizar_url(pagina["url"]) == alvo:
            return pagina
    raise HTTPException(status_code=404, detail="URL não encontrada nos dados mockados.")



