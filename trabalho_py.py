@app.get("/ler")
def ler_pagina(
    url: str = Query(..., description="URL a ser lida, ex.: https://exemplo.com"),
    max_links: int = Query(100, ge=0, le=1000),
    max_texto: int = Query(5000, ge=0, le=100000, description="Máx. de caracteres do texto"),
):
    """Devolve em JSON os dados da página correspondente à URL."""
    pagina = buscar_pagina(url)


    if "dados" in pagina:
        return {
            "url": pagina["url"],
            "status_code": pagina["status_code"],
            "content_type": pagina["content_type"],
            "dados": pagina["dados"],
        }


    return {
        "url": pagina["url"],
        "status_code": pagina["status_code"],
        "content_type": pagina["content_type"],
        "titulo": pagina["titulo"],
        "descricao": pagina["descricao"],
        "h1": pagina["h1"],
        "h2": pagina["h2"],
        "links": pagina["links"][:max_links],
        "imagens": pagina["imagens"],
        "texto": pagina["texto"][:max_texto],
    }



